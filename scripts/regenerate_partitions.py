"""Reconstruct frozen subject-fold and diagnosis-matched slice-replacement manifests.

Only source-dataset-relative paths are used. The first-seed and second-seed
training configurations share these fixed partitions; no models are trained.
"""

from __future__ import annotations

import argparse
import hashlib
import math
from pathlib import Path

import numpy as np
import pandas as pd

FOLD_SEEDS = (42, 101, 202, 303, 404)
DOSES = (0, 25, 50, 75, 100)


def records(data: Path) -> pd.DataFrame:
    frame = pd.read_csv(data / "source_relative_inventory.csv.gz")
    assert len(frame) == 42147
    assert frame.subject_token.nunique() == 68
    assert frame.dataset_relative_path.is_unique
    # Stable original anonymization key generated by the frozen code from the
    # dataset's subject folder. It is never released as a research subject ID.
    subject_folder = frame.dataset_relative_path.str.split("/").str[1]
    raw = subject_folder.map(lambda x: "S_" + hashlib.sha256(x.encode()).hexdigest()[:10])
    frame = frame.assign(_anon=raw, _path=frame.dataset_relative_path)
    assert frame.groupby("subject_token")._anon.nunique().eq(1).all()
    assert frame.groupby("_anon").subject_token.nunique().eq(1).all()
    return frame


def subject_order(test: pd.DataFrame, fold: int) -> list[str]:
    pools = {}
    for diagnosis, group in test.groupby("class_label", sort=True):
        values = sorted(group._anon.astype(str).tolist())
        rng = np.random.default_rng(FOLD_SEEDS[fold] + 1000 + int(diagnosis) * 101)
        rng.shuffle(values)
        pools[int(diagnosis)] = values
    totals = {c: len(v) for c, v in pools.items()}
    total = sum(totals.values())
    chosen = {c: 0 for c in pools}
    pos = {c: 0 for c in pools}
    result = []
    for step in range(1, total + 1):
        classes = [c for c in sorted(pools) if pos[c] < len(pools[c])]
        deficits = {c: (totals[c] / total) * step - chosen[c] for c in classes}
        cls = max(classes, key=lambda c: (deficits[c], -c))
        result.append(pools[cls][pos[cls]])
        pos[cls] += 1
        chosen[cls] += 1
    return result


def build(data: Path) -> pd.DataFrame:
    inventory = records(data)
    roles = pd.read_csv(data / "frozen_fold_roles.csv")
    assert len(roles) == 340
    keys = inventory[["subject_token", "_anon", "class_label"]].drop_duplicates()
    assert len(keys) == 68
    roles = roles.merge(keys, on=["subject_token", "class_label"], validate="many_to_one")
    out = []
    checks = []
    selected = {}
    for fold in range(5):
        r = roles[roles.outer_fold == fold]
        train_ids = set(r[r.role == "outer_training"]._anon)
        val_ids = set(r[r.role == "inner_validation"]._anon)
        test_ids = set(r[r.role == "outer_testing"]._anon)
        assert len(train_ids | val_ids | test_ids) == 68
        assert not (train_ids & val_ids or train_ids & test_ids or val_ids & test_ids)
        train = inventory[inventory._anon.isin(train_ids)]
        test = inventory[inventory._anon.isin(test_ids)]
        test_subjects = r[r.role == "outer_testing"][["_anon", "class_label"]].copy()
        order = subject_order(test_subjects, fold)
        assert len(order) == len(test_ids)
        levels = {}
        for dose in DOSES:
            n_target = 0 if dose == 0 else len(order) if dose == 100 else round(len(order) * dose / 100)
            target_ids = order[:n_target]
            levels[dose] = set(target_ids)
            selected[(fold, dose)] = set(target_ids)
            injected = []
            for rank, sid in enumerate(target_ids, 1):
                case = test[test._anon == sid].sort_values("_path").reset_index(drop=True)
                n = min(50, math.floor(len(case) * 0.2), max(0, len(case) - 2))
                assert 1 <= n <= 50 and n <= math.floor(0.2 * len(case)) and len(case) - n >= 2
                seed = FOLD_SEEDS[fold] + 20000 + int(hashlib.sha256(sid.encode()).hexdigest()[:8], 16)
                rng = np.random.default_rng(seed)
                indices = np.sort(rng.choice(len(case), size=n, replace=False))
                for rec in case.iloc[indices].itertuples(index=False):
                    out.append((fold, dose, "inject", rec.subject_token, rec.class_label, rec.dataset_relative_path))
                    injected.append(rec)
            # Class-matched replacement is a prefix of one deterministic pool.
            for cls in (0, 1):
                n_remove = sum(int(rec.class_label) == cls for rec in injected)
                candidate = train[train.class_label == cls].sort_values("_path")
                rng = np.random.default_rng(FOLD_SEEDS[fold] + 30000 + cls * 313)
                removed = candidate.iloc[rng.permutation(len(candidate))[:n_remove]]
                assert len(removed) == n_remove
                for rec in removed.itertuples(index=False):
                    out.append((fold, dose, "remove", rec.subject_token, rec.class_label, rec.dataset_relative_path))
            checks.append((fold, dose, len(injected), len(injected), len(target_ids)))
        assert levels[0] == set() and levels[100] == test_ids
        assert levels[25] <= levels[50] <= levels[75] <= levels[100]
    frame = pd.DataFrame(
        out, columns=["outer_fold", "overlap_pct", "operation", "subject_token", "class_label", "dataset_relative_path"]
    )
    assert not frame.duplicated(["outer_fold", "overlap_pct", "operation", "dataset_relative_path"]).any()
    assert (
        frame.groupby(["outer_fold", "overlap_pct", "operation"])
        .size()
        .unstack()
        .pipe(lambda d: (d.inject == d.remove).all())
    )
    # Verify subject-level dose and slice counts against the frozen original
    # evidence, rather than trusting only the new path-based calculation.
    original_injected = pd.read_csv(data / "injected_records.csv")
    count_new = (
        frame.query('operation == "inject"')
        .groupby(["outer_fold", "overlap_pct", "subject_token", "class_label"])
        .size()
        .sort_index()
    )
    count_old = (
        original_injected.groupby(["outer_fold", "overlap_pct", "subject_token", "class_label"]).size().sort_index()
    )
    pd.testing.assert_series_equal(count_new, count_old, check_names=False)
    original_removed = pd.read_csv(data / "replaced_training_records.csv")
    count_new = (
        frame.query('operation == "remove"').groupby(["outer_fold", "overlap_pct", "class_label"]).size().sort_index()
    )
    count_old = original_removed.groupby(["outer_fold", "overlap_pct", "class_label"]).size().sort_index()
    pd.testing.assert_series_equal(count_new, count_old, check_names=False)
    # Compare the reconstructed source-relative endpoint operations with the
    # independently saved second-training-seed execution manifests.
    saved = pd.read_csv(data / "second_seed_endpoint_operations.csv.gz")
    actual = frame[frame.overlap_pct == 100]
    keys = ["outer_fold", "overlap_pct", "operation", "dataset_relative_path", "class_label"]
    pd.testing.assert_frame_equal(
        actual[keys].sort_values(keys).reset_index(drop=True),
        saved[keys].sort_values(keys).reset_index(drop=True),
        check_like=False,
    )
    return frame


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=Path(__file__).resolve().parents[1] / "data")
    parser.add_argument("--out", type=Path, default=Path("outputs/partitions.csv.gz"))
    args = parser.parse_args()
    df = build(args.data_dir)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(args.out, index=False, compression="gzip")
    print(f"Verified {len(df)} frozen injection/removal records for five folds and five overlap levels.")


if __name__ == "__main__":
    main()
